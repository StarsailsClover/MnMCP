def fix_block_mappings():
    """修正方块映射"""
    data_dir = Path(__file__).parent / "data"
    if not data_dir.exists():
        data_dir = Path("data")
    
    # 读取Go映射（权威来源，2228条）
    go_path = data_dir / "mnw_block_mapping_from_go.json"
    with open(go_path, 'r', encoding='utf-8') as f:
        go_data = json.load(f)
    
    # 构建统一映射
    unified_mappings = []
    mc_name_to_bedrock_id = BEDROCK_BLOCK_IDS
    
    unmapped_count = 0
    mapped_count = 0
    
    for entry in go_data["mappings"]:
        mnw_id = entry["mnw_id"]
        mc_name = entry["mc_name"]
        
        # 查找Bedrock数字ID
        bedrock_id = mc_name_to_bedrock_id.get(mc_name, None)
        
        if bedrock_id is None:
            # 尝试加minecraft:前缀
            mc_name_clean = mc_name.replace("minecraft:", "")
            bedrock_id = mc_name_to_bedrock_id.get(mc_name_clean, None)
        
        if bedrock_id is None:
            bedrock_id = -1  # 未映射
            unmapped_count += 1
        else:
            mapped_count += 1
        
        unified_entry = {
            "mnw_id": mnw_id,
            "mnw_name_cn": entry.get("mnw_name_cn", ""),
            "mnw_name_en": entry.get("mnw_name_en", ""),
            "mc_registry": f"minecraft:{mc_name}" if not mc_name.startswith("minecraft:") else mc_name,
            "mc_bedrock_id": bedrock_id,
            "texture": entry.get("texture", "-"),
            "source": entry.get("source", "unknown"),
            "verified": bedrock_id >= 0,
        }
        unified_mappings.append(unified_entry)
    
    # 写入统一映射文件
    output = {
        "version": "2.0.0",
        "format": "unified",
        "mc_version": "1.20.6",
        "mc_protocol": "Bedrock",
        "mnw_version": "1.53.1",
        "last_updated": "2026-03-01",
        "note": "统一方块映射 - 基于Go社区映射(2228条) + Bedrock版数字ID修正",
        "important": "mc_bedrock_id 是 Bedrock Edition 的数字ID，不是 Java Edition 1.13+ 的ID",
        "total_mappings": len(unified_mappings),
        "mapped_count": mapped_count,
        "unmapped_count": unmapped_count,
        "mappings": unified_mappings,
    }
    
    output_path = data_dir / "block_mapping_unified.json"
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(output, f, indent=2, ensure_ascii=False)
    
    print(f"统一映射已生成: {output_path}")
    print(f"  总映射: {len(unified_mappings)}")
    print(f"  已映射: {mapped_count}")
    print(f"  未映射: {unmapped_count}")
    
    return output_path


if __name__ == "__main__":
    fix_block_mappings()
